# Generates native/nwbmotif_dict.h (the motif dictionary of bmotif 2.0.2 used by the kernel 50 of the core plugin)
# and prints the position ranges for the help file.
#   Rscript tools/gen_bmotif_dict.R <bmotif library dir or "">  [output file]
args <- commandArgs(TRUE)
lib <- if (length(args) >= 1 && nzchar(args[1])) args[1] else NULL
outfile <- if (length(args) >= 2) args[2] else "native/nwbmotif_dict.h"
suppressMessages(library(bmotif, lib.loc = lib))
perms <- function(v) { if (length(v)<=1) return(list(v)); out <- list(); for (i in seq_along(v)) for (p in perms(v[-i])) out[[length(out)+1]] <- c(v[i], p); out }
connected <- function(M) {
  a <- nrow(M); b <- ncol(M); n <- a+b
  A <- matrix(0,n,n); A[1:a,(a+1):n] <- M; A[(a+1):n,1:a] <- t(M)
  seen <- 1; fr <- 1
  while (length(fr)) { nx <- which(colSums(A[fr,,drop=FALSE])>0); nx <- setdiff(nx, seen); seen <- c(seen,nx); fr <- nx }
  length(seen)==n
}
canon <- function(M) { a<-nrow(M); b<-ncol(M); best<-NULL
  for (pr in perms(1:a)) for (pc in perms(1:b)) { s <- paste(M[pr,pc], collapse=""); if (is.null(best)||s<best) best<-s }
  best }
rows <- list()
for (a in 1:5) for (b in 1:5) if (a+b<=6) {
  seen <- c()
  for (code in 0:(2^(a*b)-1)) {
    M <- matrix(as.integer(intToBits(code))[1:(a*b)], a, b)
    if (!connected(M)) next
    cn <- canon(M); if (cn %in% seen) next; seen <- c(seen, cn)
    mc <- mcount(M, six_node=TRUE, normalisation=FALSE, mean_weight=FALSE, standard_dev=FALSE)
    id <- which(mc$nodes==a+b & mc$frequency==1)
    stopifnot(length(id)==1)
    np <- as.matrix(node_positions(M, six_node=TRUE, weights_method="none"))
    mp <- bmotif:::motif_info(id, node=TRUE, link=FALSE)
    pos <- sapply(1:(a+b), function(v) { w <- which(np[v,mp]>0); stopifnot(length(w)==1, np[v,mp[w]]==1); mp[w] })
    rows[[length(rows)+1]] <- list(id=id,a=a,b=b,M=M,pos=pos, np=mp)
  }
}
rows <- rows[order(sapply(rows, function(r) r$id))]
stopifnot(length(rows)==44, all(sapply(rows,function(r) r$id)==1:44))
# side check of positions against rowcolumn
for (r in rows) { rc <- sapply(r$pos, bmotif:::rowcolumn); stopifnot(all(rc==c(rep("row",r$a),rep("column",r$b)))) }
con <- file(outfile, "w")
writeLines(c("/* generated by tools/gen_bmotif_dict.R from bmotif 2.0.2 (motif_info, mcount, node_positions); do not edit */",
 "/* motif id (1-based, in order), rows a, columns b, adjacency: row i has bit j set when it is tied to column j, position ids: rows then columns */",
 "typedef struct { int a, b, adj[5], pos[6]; } n380_proto_t;",
 "static const n380_proto_t N380_PROTO[44] = {"), con)
for (k in seq_along(rows)) { r <- rows[[k]]
  adj <- sapply(1:r$a, function(i) sum(r$M[i,] * 2^(0:(r$b-1))))
  adj <- c(adj, rep(0, 5-r$a)); pos <- c(r$pos, rep(0, 6-length(r$pos)))
  writeLines(sprintf("\t{ %d, %d, {%s}, {%s} }%s", r$a, r$b, paste(adj,collapse=","), paste(pos,collapse=","), if (k<44) "," else ""), con) }
writeLines("};", con)
close(con)
cat("wrote", outfile, "\n")
