# Writes cscripts/test_nwergm_structural.do: embedded test networks + R ergm 4.12.0 reference values
#   (a) summary() of every term on a small undirected and a small directed network
#   (b) MPLE coefficients/SE (ergm(estimate="MPLE")) of non-degenerate models on und_c (60 nodes) / dir_c (40 nodes)
suppressMessages({library(ergm); library(network)})
sp <- read.csv("spec.csv", stringsAsFactors=FALSE)
set.seed(4242)
mk_und <- function(n, p) { U <- matrix(0,n,n); U[upper.tri(U)] <- rbinom(n*(n-1)/2,1,p); U+t(U) }
mk_dir <- function(n, p) { D <- matrix(rbinom(n*n,1,p),n,n); diag(D) <- 0; D }
U <- mk_und(14, .3); D <- mk_dir(12, .22)
aU <- sample(1:3, 14, TRUE); aD <- sample(1:3, 12, TRUE)
rows <- function(M) apply(M, 1, paste, collapse="")
nwU <- network(U, directed=FALSE); nwU %v% "a" <- aU
nwD <- network(D, directed=TRUE); nwD %v% "a" <- aD
out <- character()
w <- function(...) out <<- c(out, sprintf(...))
w("cscript")
w("")
w("capture adopath ++ \".\"")
w("capture adopath ++ \"lib\"")
w("do unw_ergm.do")
w("")
w("* Certifies the structural ergm terms of nwergm's structural() option (non-bipartite):")
w("*  (1) observed statistic == R ergm 4.12.0 summary() on a small undirected and a small directed network,")
w("*  (2) MPLE coefficients and standard errors == R ergm(estimate=\"MPLE\") on a 60-node and a 40-node network,")
w("*  (3) native change statistics == brute-force differences of the observed statistic (random graphs),")
w("*  (4) MCMLE / simulate / error smoke tests.")
w("* Reference values were produced by dev/E3/gen_test_structural.R (this file is generated by it).")
w("capture adopath ++ \"lib/plugins/macos\"")
w("capture adopath ++ \"lib/plugins/unix\"")
w("capture adopath ++ \"lib/plugins/windows\"")
w("")
w("mata:")
w("mata set matastrict off")
w("void ns_t_fill(class ErgmGraph G, real matrix A, real scalar dir){")
w("	real scalar i, j, n")
w("	n = rows(A)")
w("	G.init(n, dir)")
w("	for (i=1; i<=n; i++) for (j=1; j<=n; j++) {")
w("		if (i == j) continue")
w("		if (!dir & j < i) continue")
w("		if (A[i,j] != 0) G.toggle(i,j)")
w("	}")
w("}")
w("end")
w("")
w("capture program drop ns_stat")
w("program ns_stat")
w("	args net dir terms")
w("	mata: __nwergm_last_M = ErgmModel()")
w("	mata: __nwergm_last_M.init()")
w("	mata: __nwergm_last_G = ErgmGraph()")
w("	mata: ns_t_fill(__nwergm_last_G, st_matrix(\"A_`net'\"), `dir')")
w("	qui _nwergm_struct `net', terms(`terms') nodes(`=rowsof(A_`net')') directed(`=cond(`dir',\"true\",\"false\")')")
w("	mata: st_matrix(\"__ns_S\", __nwergm_last_M.full_statistic(__nwergm_last_G))")
w("end")
w("")
w("capture program drop ns_check")
w("program ns_check")
w("	args id net dir terms expected")
w("	ns_stat `net' `dir' \"`terms'\"")
w("	local k : word count `expected'")
w("	assert colsof(__ns_S) == `k'")
w("	forvalues j = 1/`k' {")
w("		local e : word `j' of `expected'")
w("		if abs(__ns_S[1,`j'] - `e') > 1e-6 {")
w("			di as err \"FAIL statistic `id' on `net': coefficient `j' is \" __ns_S[1,`j'] \" but R gives `e'\"")
w("			exit 9")
w("		}")
w("	}")
w("end")
w("")
for (nm in c("U","D")) {
  M <- get(nm); a <- get(paste0("a",nm))
  w("matrix A_%s = J(%d,%d,0)", tolower(nm), nrow(M), nrow(M))
  for (i in 1:nrow(M)) for (j in 1:ncol(M)) if (M[i,j]==1) w("matrix A_%s[%d,%d] = 1", tolower(nm), i, j)
  w("* node attribute a of %s", tolower(nm))
}
w("clear")
w("set obs 14")
w("gen a = .")
for (i in 1:14) w("qui replace a = %d in %d", aU[i], i)
w("tempfile attU")
w("qui save `attU'")
w("clear")
w("set obs 12")
w("gen a = .")
for (i in 1:12) w("qui replace a = %d in %d", aD[i], i)
w("tempfile attD")
w("qui save `attD'")
w("")
cnt <- 0
for (i in seq_len(nrow(sp))) {
  for (nt in c("U","D")) {
    k <- sp$kind[i]
    if (k=="und" && nt=="D") next; if (k=="dir" && nt=="U") next
    nw <- if (nt=="U") nwU else nwD
    f <- as.formula(paste("nw ~", sp$r[i]))
    s <- tryCatch(suppressWarnings(summary(f)), error=function(e) NULL)
    if (is.null(s)) next
    s <- s[names(s) != "edges"]
    if (sp$id[i] %in% c("density","meandeg")) s <- s
    w("use `att%s', clear", nt)
    w("ns_check %s_%s %s %d \"%s\" \"%s\"", sp$id[i], nt, tolower(nt), as.integer(nt=="D"), gsub("\"","",sp$nw[i]), paste(format(as.numeric(s), digits=15), collapse=" "))
    cnt <- cnt + 1
  }
}
w("di \"test_nwergm_structural: %d statistics match R summary()\"", cnt)
w("")
# ---------------- MPLE comparison -------------------
R <- read.csv("ref_mple.csv", stringsAsFactors=FALSE)
nets <- list(und_c=as.matrix(read.csv("und_c_adj.csv", header=FALSE)), dir_c=as.matrix(read.csv("dir_c_adj.csv", header=FALSE)))
nd <- list(und_c=read.csv("und_c_nodes.csv"), dir_c=read.csv("dir_c_nodes.csv"))
w("* ---- (2) MPLE ----")
w("capture program drop ns_mple")
w("program ns_mple")
w("	args id net dir terms edges")
w("	qui nwclear")
w("	qui clear")
w("	qui nwset, mat(M_`net') `=cond(`dir',\"directed\",\"undirected\")' name(g)")
w("	qui svmat NA_`net', names(col)")
w("	qui nwergm g, `edges' structural(`terms') method(mple)")
w("	matrix b = e(b)")
w("	matrix V = e(V)")
w("end")
w("capture program drop ns_cmp")
w("program ns_cmp")
w("	args id j coef se")
w("	if abs(b[1,`j'] - `coef') > 1e-4 * max(1, abs(`coef')) {")
w("		di as err \"FAIL MPLE `id': coefficient `j' is \" b[1,`j'] \" but R gives `coef'\"")
w("		exit 9")
w("	}")
w("	if abs(sqrt(V[`j',`j']) - `se') > 2e-3 * max(1, `se') {")
w("		di as err \"FAIL MPLE `id': SE `j' is \" sqrt(V[`j',`j']) \" but R gives `se'\"")
w("		exit 9")
w("	}")
w("end")
for (nm in names(nets)) {
  M <- nets[[nm]]; n <- nrow(M)
  w("matrix M_%s = J(%d,%d,0)", nm, n, n)
  for (i in 1:n) { js <- which(M[i,]==1); if (length(js)) w("forvalues j = 1/%d {\n\tif inlist(`j', %s) matrix M_%s[%d,`j'] = 1\n}", n, paste(js, collapse=","), nm, i) }
  w("matrix NA_%s = J(%d,1,0)", nm, n)
  for (i in 1:n) w("matrix NA_%s[%d,1] = %d", nm, i, nd[[nm]]$a[i])
  w("matrix colnames NA_%s = a", nm)
}
mp <- 0
for (i in seq_len(nrow(sp))) for (nm in names(nets)) {
  k <- sp$kind[i]; isd <- grepl("dir", nm)
  if (k=="und" && isd) next; if (k=="dir" && !isd) next
  r <- R[R$net==nm & R$id==sp$id[i],]
  if (nrow(r)==0 || any(!is.finite(r$rcoef[!is.na(r$rcoef)])) || any(r$rse[!is.na(r$rcoef)] > 20 & !(sp$id[i] %in% c("density","meandeg")))) next
  if (any(is.na(r$rcoef))) next
  if (sp$id[i] %in% c("opentriad")) next
  edges <- if (sp$id[i] %in% c("density","meandeg")) "" else "edges"
  w("ns_mple %s_%s %s %d \"%s\" \"%s\"", sp$id[i], nm, nm, as.integer(isd), gsub("\"","",sp$nw[i]), edges)
  for (j in seq_len(nrow(r))) w("ns_cmp %s_%s %d %.12g %.12g", sp$id[i], nm, j, r$rcoef[j], r$rse[j])
  mp <- mp + 1
}
w("di \"test_nwergm_structural: %d MPLE fits match R\"", mp)
w("")
tail <- readLines("test_tail.do.txt")
writeLines(c(out, tail), "../../cscripts/test_nwergm_structural.do")
cat("terms:", cnt, " mple models:", mp, "\n")
