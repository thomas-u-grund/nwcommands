suppressMessages(library(ergm))
rd <- function(f) as.matrix(read.csv(f, header=FALSE))
data(florentine)
f <- ergm(flomarriage ~ edges + triangle, estimate="MPLE")
g <- gof(f, GOF=~degree+espartners+dspartners+distance+triadcensus+model, control=control.gof.ergm(nsim=3))
cat("FLO deg:", g$obs.deg, "\nFLO esp:", g$obs.espart, "\nFLO dsp:", g$obs.dspart, "\nFLO dist:", g$obs.dist, "\nFLO tri:", g$obs.triadcensus, "\n")
sam <- network(rd("sam_adj.csv"), directed=TRUE)
f2 <- ergm(sam ~ edges + mutual, estimate="MPLE")
g2 <- gof(f2, GOF=~idegree+odegree+espartners+dspartners+distance+triadcensus+model, control=control.gof.ergm(nsim=3))
cat("SAM ideg:", g2$obs.ideg, "\nSAM odeg:", g2$obs.odeg, "\nSAM esp:", g2$obs.espart, "\nSAM dsp:", g2$obs.dspart, "\nSAM dist:", g2$obs.dist, "\nSAM tri:", g2$obs.triadcensus, "\n")
